#!/usr/bin/env node
// Writes cluckwise/tasks-inline.css: Tasks' styles (and the Bootstrap it loads) fenced to #cwRoot, for Tasks running in
// ProdWise's own page (js/tasksinline.js). Done once per release so phones don't rewrite 1.3 MB of styles every time
// they open Tasks. Run it after changing Tasks' <style> (tests/smoke.js fails until you do):
//   node tools/build-tasks-css.js
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.join(__dirname, '..');
const { scopeCss } = require(path.join(ROOT, 'js', 'cwscope.js'));

function sources(){
  const html = fs.readFileSync(path.join(ROOT, 'cluckwise', 'index.html'), 'utf8');
  const head = html.slice(0, html.indexOf('</head>'));
  const styles = [...head.matchAll(/<style>([\s\S]*?)<\/style>/g)].map(m => m[1]).join('\n');
  const links = [...head.matchAll(/<link rel="stylesheet" href="([^"]+)"/g)].map(m => m[1]).filter(h => !/fonts\.googleapis/.test(h));
  const vendor = links.map(h => {
    const m = h.match(/bootstrap\/([\d.]+)\/css\/bootstrap\.min\.css$/);
    if(!m) throw new Error('Tasks loads a style sheet this build does not know: ' + h);
    const f = path.join(__dirname, 'vendor', `bootstrap-${m[1]}.min.css`);
    if(!fs.existsSync(f)) throw new Error(`Save ${h} as ${path.relative(ROOT, f)} first`);
    return fs.readFileSync(f, 'utf8');
  });
  const scoper = fs.readFileSync(path.join(ROOT, 'js', 'cwscope.js'), 'utf8');
  const sig = crypto.createHash('sha1').update(links.join('|') + '\n' + styles + '\n' + scoper).digest('hex').slice(0, 16);
  return { styles, vendor, sig };
}
function build(){
  const { styles, vendor, sig } = sources();
  const out = `/* GENERATED by tools/build-tasks-css.js from cluckwise/index.html — do not edit. source ${sig} */\n`
    + vendor.map(v => scopeCss(v.replace(/@charset[^;]*;/g, ''))).join('\n') + '\n' + scopeCss(styles) + '\n';
  fs.writeFileSync(path.join(ROOT, 'cluckwise', 'tasks-inline.css'), out);
  return { sig, bytes: out.length };
}
// for tests/smoke.js: is the file up to date?
function upToDate(){
  const f = path.join(ROOT, 'cluckwise', 'tasks-inline.css');
  if(!fs.existsSync(f)) return false;
  const head = fs.readFileSync(f, 'utf8').slice(0, 200), m = head.match(/source ([0-9a-f]{16})/);
  return !!m && m[1] === sources().sig;
}
module.exports = { build, upToDate };
if(require.main === module){ const r = build(); console.log(`cluckwise/tasks-inline.css written (${Math.round(r.bytes / 1024)} KB, source ${r.sig})`); }
